const DEFAULT_LEAVE_TOTALS: Record<LeaveType, number> = {
  annual: 18,
  sick: 10,
  unpaid: 5,
  family: 3,
};

export const ONBOARDING_STEPS: { id: string; label: string }[] = [
  { id: "personal-info", label: "Personal information" },
  { id: "role-details", label: "Role and reporting line" },
  { id: "salary-setup", label: "Salary and banking setup" },
  { id: "documents", label: "Document collection" },
  { id: "equipment", label: "Equipment and access provisioning" },
  { id: "induction", label: "Induction and orientation" },
];

export function defaultLeaveBalances(): LeaveBalance[] {
  return leaveBalances();
}

function leaveBalances(used?: Partial<Record<LeaveType, number>>): LeaveBalance[] {
  return (Object.keys(DEFAULT_LEAVE_TOTALS) as LeaveType[]).map((type) => ({
    type,
    total: DEFAULT_LEAVE_TOTALS[type],
    used: used?.[type] ?? 0,
  }));
}

export function onboardingPlan(stepsComplete: number, startDate: string, buddy?: string): Onboarding {
  const steps = ONBOARDING_STEPS.map((step, idx) => ({
    ...step,
    complete: idx < stepsComplete,
  }));
  return {
    progress: Math.round((stepsComplete / ONBOARDING_STEPS.length) * 100),
    startDate,
    buddy,
    steps,
  };
}

interface EmployeeSeed {
  num: number;
  tenantId: string;
  numberPrefix: string;
  firstName: string;
  lastName: string;
  emailDomain: string;
  phone: string;
  jobTitle: string;
  department: string;
  employmentType?: EmploymentType;
  status?: EmploymentStatus;
  startDate: string;
  location: string;
  managerId?: string;
  annualGross: number;
  travelAllowance?: number;
  housingAllowance?: number;
  pensionContributionPct?: number;
  medicalAid?: number;
  bank: string;
  accountNumber: string;
  branchCode: string;
  accountType: "Cheque" | "Savings";
  taxNumber: string;
  idNumber: string;
  address: string;
  emergencyContact: { name: string; relationship: string; phone: string };
  leaveUsed?: Partial<Record<LeaveType, number>>;
  onboarding?: Onboarding;
}

function buildEmployee(seed: EmployeeSeed): Employee {
  return {
    id: `${seed.tenantId}-emp-${String(seed.num).padStart(3, "0")}`,
    tenantId: seed.tenantId,
    employeeNumber: `${seed.numberPrefix}-${String(seed.num).padStart(4, "0")}`,
    firstName: seed.firstName,
    lastName: seed.lastName,
    email: `${seed.firstName.toLowerCase()}.${seed.lastName.toLowerCase()}@${seed.emailDomain}`,
    phone: seed.phone,
    avatarColor: AVATAR_COLORS[seed.num % AVATAR_COLORS.length],
    initials: getInitials(seed.firstName, seed.lastName),
    jobTitle: seed.jobTitle,
    department: seed.department,
    employmentType: seed.employmentType ?? "full_time",
    status: seed.status ?? "active",
    startDate: seed.startDate,
    location: seed.location,
    managerId: seed.managerId,
    salary: {
      annualGross: seed.annualGross,
      currency: "ZAR",
      payFrequency: "monthly",
      travelAllowance: seed.travelAllowance,
      housingAllowance: seed.housingAllowance,
      pensionContributionPct: seed.pensionContributionPct ?? 0.075,
      medicalAid: seed.medicalAid,
    },
    bankDetails: {
      bank: seed.bank,
      accountNumber: seed.accountNumber,
      branchCode: seed.branchCode,
      accountType: seed.accountType,
    },
    taxNumber: seed.taxNumber,
    idNumber: seed.idNumber,
    address: seed.address,
    emergencyContact: seed.emergencyContact,
    leaveBalances: leaveBalances(seed.leaveUsed),
    onboarding: seed.onboarding,
  };
}

